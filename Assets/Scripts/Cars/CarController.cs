    void OnValidate()
    {
        if (Application.isPlaying && Колёса != null && Колёса.Length > 0)
        {
            ConfigureWheelColliders();
            CacheDefaultFrictionSettings();
            
            if (ИспользоватьНитро)
            {
                ТекущийЗапасНитро = Mathf.Min(ТекущийЗапасНитро, МаксимальныйЗапасНитро);
                ОбновитьРасчетныеЗначения();
            }
            
            // Обновляем массивы КПП при изменении количества передач
            if (ИспользоватьКПП)
            {
                if (МножителиМощностиПоПередачам == null || МножителиМощностиПоПередачам.Length != КоличествоПередач + 1)
                {
                    МножителиМощностиПоПередачам = new float[КоличествоПередач + 1];
                    for (int i = 0; i <= КоличествоПередач; i++)
                    {
                        if (i == 0) МножителиМощностиПоПередачам[i] = 0.5f;
                        else МножителиМощностиПоПередачам[i] = 0.8f + (i * 0.15f);
                    }
                }
                
                if (МаксСкоростиПоПередачам == null || МаксСкоростиПоПередачам.Length != КоличествоПередач + 1)
                {
                    МаксСкоростиПоПередачам = new float[КоличествоПередач + 1];
                    for (int i = 0; i <= КоличествоПередач; i++)
                    {
                        if (i == 0) МаксСкоростиПоПередачам[i] = 20f;
                        else МаксСкоростиПоПередачам[i] = 30f + ((i-1) * 25f);
                    }
                }
            }
        }
    }

