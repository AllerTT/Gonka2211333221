    void Start()
    {
        rb = GetComponent<Rigidbody>();
        
        // Устанавливаем массу автомобиля
        исходнаяМасса = МассаАвтомобиля;
        rb.mass = МассаАвтомобиля;
        
        // Настройка центра масс для стабильности
        rb.centerOfMass = new Vector3(0, ВысотаЦентраМасс, 0);
        
        // Настройка сопротивлений
        rb.linearDamping = СопротивлениеВоздуха;
        rb.angularDamping = СопротивлениеВращению;
        
        // Инициализация КПП
        ИнициализироватьКПП();

        if (Колёса.Length != 4)
        {
            Debug.LogError("Нужно ровно 4 WheelCollider!");
            return;
        }

        // Сортировка колёс: передние/задние по Z
        var sorted = Колёса.OrderBy(w => w.transform.localPosition.z).ToArray();
        rearWheels = new[] { sorted[0], sorted[1] };
        frontWheels = new[] { sorted[2], sorted[3] };

        // Настройка колёс
        ConfigureWheelColliders();
        
        // Сохранение настроек трения по умолчанию
        CacheDefaultFrictionSettings();
        
        // Инициализация нитро и текущих значений
        ИнициализироватьРасчетныеЗначения();
        
        // Ограничение начального запаса нитро
        ТекущийЗапасНитро = Mathf.Min(ТекущийЗапасНитро, МаксимальныйЗапасНитро);
        
        // Инициализация отладки
        предыдущаяСкорость = rb.linearVelocity.magnitude;
    }

    void ИнициализироватьКПП()
    {
        if (!ИспользоватьКПП) return;
        
        // Проверяем и инициализируем массивы для КПП
        if (МножителиМощностиПоПередачам == null || МножителиМощностиПоПередачам.Length != КоличествоПередач + 1)
        {
            МножителиМощностиПоПередачам = new float[КоличествоПередач + 1];
            for (int i = 0; i <= КоличествоПередач; i++)
            {
                if (i == 0) МножителиМощностиПоПередачам[i] = 0.5f; // Задняя
                else МножителиМощностиПоПередачам[i] = 0.8f + (i * 0.15f);
            }
        }
        
        if (МаксСкоростиПоПередачам == null || МаксСкоростиПоПередачам.Length != КоличествоПередач + 1)
        {
            МаксСкоростиПоПередачам = new float[КоличествоПередач + 1];
            for (int i = 0; i <= КоличествоПередач; i++)
            {
                if (i == 0) МаксСкоростиПоПередачам[i] = 20f; // Задняя
                else МаксСкоростиПоПередачам[i] = 30f + ((i-1) * 25f);
            }
        }
        
        // Устанавливаем начальные значения
        текущаяПередача = 1;
        множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[текущаяПередача];
        максСкоростьТекущейПередачи = МаксСкоростиПоПередачам[текущаяПередача];
    }

    void ИнициализироватьРасчетныеЗначения()
    {
        текущаяМощностьДвигателя = БазоваяМощностьДвигателя;
        текущаяМаксимальнаяСкорость = БазоваяМаксимальнаяСкорость;
    }

    void ConfigureWheelColliders()
    {
        foreach (var wc in Колёса)
        {
            // Настройка подвески из инспектора
            wc.suspensionDistance = ХодПодвески;
            wc.suspensionSpring = new JointSpring
            {
                spring = ЖёсткостьПружины,
                damper = СилаДемпфирования,
                targetPosition = ЦелеваяПозицияПружины
            };

            // Настройка сцепления
            var forwardFriction = wc.forwardFriction;
            forwardFriction.stiffness = ПродольноеСцепление;
            wc.forwardFriction = forwardFriction;

            var sidewaysFriction = wc.sidewaysFriction;
            sidewaysFriction.stiffness = БоковоеСцепление;
            wc.sidewaysFriction = sidewaysFriction;
        }
    }

    WheelCollider[] GetDriveWheels()
    {
        switch (типПривода)
        {
            case ТипПривода.ЗаднийПривод:
                return rearWheels;
            case ТипПривода.ПереднийПривод:
                return frontWheels;
            case ТипПривода.ПолныйПривод:
                return Колёса;
            default:
                return rearWheels;
        }
    }

    float GetDriveMultiplier()
    {
        switch (типПривода)
        {
            case ТипПривода.ЗаднийПривод:
                return МножительЗаднегоПривода;
            case ТипПривода.ПереднийПривод:
                return 1f;
            case ТипПривода.ПолныйПривод:
                return 1f;
            default:
                return 1f;
        }
    }

    void CacheDefaultFrictionSettings()
    {
        if (Колёса.Length > 0)
        {
            defaultForwardFriction = Колёса[0].forwardFriction;
            defaultSidewaysFriction = Колёса[0].sidewaysFriction;
            
            handbrakeSidewaysFriction = defaultSidewaysFriction;
            handbrakeSidewaysFriction.stiffness = СцеплениеПриДрифте;
        }
    }

    void Update()
    {
        // Получение ввода
        float horizontal = Input.GetAxis("Horizontal");
        float vertical = Input.GetAxis("Vertical");
        bool handbrake = Input.GetKey(KeyCode.Space);

        // Обработка поворота
        HandleSteering(horizontal);
        
        // Обработка движения и торможения
        HandleMotorAndBrake(vertical, handbrake);
        
        // Обработка ручного тормоза
        HandleHandbrake(handbrake);
        
        // Обработка нитро
        HandleNitro(vertical);
        
        // Обработка КПП (в Update для ручного переключения)
        ОбработатьКППInput();
        
        // Накат
        rb.linearDamping = (Mathf.Abs(vertical) < 0.1f && !handbrake) ? ТорможениеНакатом : 0f;
        
        // Отладка нитро
        DebugNitroInfo();
        
        // Расчет данных для отладки
        CalculateDebugData();
        
        // Обновление значений при изменении в инспекторе
        ОбновитьРасчетныеЗначения();
        
        // Обработка наклона кузова при повороте (визуальный)
        ОбработатьНаклонКузова(horizontal);
    }

    void ОбновитьРасчетныеЗначения()
    {
        if (!нитроАктивно)
        {
            текущаяМощностьДвигателя = БазоваяМощностьДвигателя;
            текущаяМаксимальнаяСкорость = БазоваяМаксимальнаяСкорость;
        }
    }

    void CalculateDebugData()
    {
        float текущаяСкорость = rb.linearVelocity.magnitude;
        текущееУскорение = (текущаяСкорость - предыдущаяСкорость) / Time.deltaTime;
        предыдущаяСкорость = текущаяСкорость;
        
        последниеСкорости.Add(текущаяСкорость);
        if (последниеСкорости.Count > КоличествоОтсчетов)
        {
            последниеСкорости.RemoveAt(0);
        }
        
        максимальнаяСилаТормоза = 0f;
        foreach (var колесо in Колёса)
        {
            if (колесо.brakeTorque > максимальнаяСилаТормоза)
                максимальнаяСилаТормоза = колесо.brakeTorque;
        }
        
        float maxRPM = 0;
        foreach (var колесо in Колёса)
        {
            if (колесо.rpm > maxRPM) maxRPM = колесо.rpm;
        }
        максимальныеОбороты = maxRPM;
    }

    void HandleSteering(float horizontalInput)
    {
        if (horizontalInput != 0)
        {
            // Учитываем инерцию поворота
            float инерцияФактор = Mathf.Lerp(1f, 0.7f, инерцияПоворота.magnitude * 0.1f);
            
            float speedFactor = Mathf.Clamp01(rb.linearVelocity.magnitude * ВлияниеСкоростиНаПоворот);
            float dynamicSteerAngle = МаксимальныйУголПоворота * (1f - speedFactor * 0.5f) * инерцияФактор;
            
            // В воздухе руль работает слабее
            if (вВоздухе)
            {
                dynamicSteerAngle *= 0.5f;
            }
            
            currentSteerAngle = horizontalInput * dynamicSteerAngle;
            
            // Вычисляем целевой наклон кузова при повороте
            целевойНаклонКузова = -horizontalInput * МаксимальныйНаклонКузова * Mathf.Clamp01(rb.linearVelocity.magnitude / 20f);
        }
        else
        {
            currentSteerAngle = Mathf.Lerp(currentSteerAngle, 0f, Time.deltaTime * СкоростьВозвратаРуля);
            целевойНаклонКузова = 0f;
        }

        foreach (var wheel in frontWheels)
        {
            wheel.steerAngle = currentSteerAngle;
        }
    }

    void ОбработатьНаклонКузова(float horizontalInput)
    {
        // Плавный наклон кузова при повороте
        текущийНаклонКузова = Mathf.Lerp(текущийНаклонКузова, целевойНаклонКузова, Time.deltaTime * СкоростьНаклонаКузова);
        
        // Применяем наклон только к визуальной модели (не к физике)
        // В вашем случае, если модель отдельно, нужно вращать модель, а не весь объект
        // Если модель привязана к Rigidbody, нужно осторожно вращать
        if (Mathf.Abs(текущийНаклонКузова) > 0.1f)
        {
            // Вращаем только по оси Z (крен)
            Quaternion targetRotation = Quaternion.Euler(transform.eulerAngles.x, transform.eulerAngles.y, текущийНаклонКузова);
            transform.rotation = Quaternion.Slerp(transform.rotation, targetRotation, Time.deltaTime * СкоростьНаклонаКузова * 0.5f);
        }
    }

    void HandleMotorAndBrake(float verticalInput, bool handbrake)
    {
        float currentSpeed = rb.linearVelocity.magnitude;
        float forwardSpeed = Vector3.Dot(rb.linearVelocity, transform.forward);
        bool isMovingForward = forwardSpeed > 0.5f;
        bool isMovingBackward = forwardSpeed < -0.5f;
        
        WheelCollider[] driveWheels = GetDriveWheels();
        float множительПривода = GetDriveMultiplier();
        
        // Применяем инерцию разгона
        float множительИнерции = инерцияРазгона;
        
        foreach (var wheel in Колёса)
        {
            wheel.motorTorque = 0f;
            wheel.brakeTorque = 0f;
        }
        
        if (handbrake)
        {
            foreach (var wheel in rearWheels)
            {
                wheel.brakeTorque = СилаРучногоТормоза;
            }
            foreach (var wheel in frontWheels)
            {
                wheel.brakeTorque = СилаРучногоТормоза * 0.3f;
            }
            return;
        }
        
        if (verticalInput > 0.1f)
        {
            // Рассчитываем максимальную скорость с учетом КПП
            float максСкоростьДляРасчетов = ИспользоватьКПП ? максСкоростьТекущейПередачи / 3.6f : текущаяМаксимальнаяСкорость;
            
            if (currentSpeed < максСкоростьДляРасчетов || forwardSpeed < 0)
            {
                float accelerationPower = Mathf.Pow(verticalInput, КриваяРазгона);
                
                // Учитываем КПП, инерцию и рывок при переключении
                float множительКПП = ИспользоватьКПП ? множительМощностиТекущейПередачи : 1f;
                
                // Добавляем эффект рывка при переключении
                float множительРывка = 1f;
                if (вРежимеРывка)
                {
                    множительРывка = СилаРывкаПриПереключении;
                }
                
                float итоговаяМощность = текущаяМощностьДвигателя * множительПривода * множительКПП * множительИнерции * множительРывка;
                
                foreach (var wheel in driveWheels)
                {
                    wheel.motorTorque = accelerationPower * итоговаяМощность;
                }
            }
            
            if (isMovingBackward)
            {
                foreach (var wheel in Колёса)
                {
                    wheel.brakeTorque = СилаТормоза * 0.8f;
                }
            }
            return;
        }
        
        if (verticalInput < -0.1f)
        {
            // Для заднего хода используем 0 передачу
            if (ИспользоватьКПП && !вПроцессеПереключения)
            {
                текущаяПередача = 0;
                множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[0];
                максСкоростьТекущейПередачи = МаксСкоростиПоПередачам[0];
            }
            
            float скоростьВперёдКмч = forwardSpeed * 3.6f;
            
            if (скоростьВперёдКмч > 5f)
            {
                float силаТорможения = СилаТормоза;
                
                foreach (var wheel in Колёса)
                {
                    wheel.brakeTorque = силаТорможения;
                }
            }
            else
            {
                float reverseInput = Mathf.Abs(verticalInput);
                float reversePower = Mathf.Pow(reverseInput, КриваяРазгона);
                
                // Мощность для заднего хода с учетом инерции
                float мощностьЗаднегоХодаСИнерцией = МощностьЗаднегоХода * множительИнерции;
                
                foreach (var wheel in driveWheels)
                {
                    wheel.motorTorque = -reversePower * мощностьЗаднегоХодаСИнерцией;
                }
                
                if (isMovingBackward && Mathf.Abs(forwardSpeed) > МаксСкоростьНазад)
                {
                    foreach (var wheel in Колёса)
                    {
                        wheel.brakeTorque = СилаТормоза * 0.5f;
                    }
                }
                
                if (скоростьВперёдКмч > 0.5f && скоростьВперёдКмч <= 5f)
                {
                    foreach (var wheel in Колёса)
                    {
                        wheel.brakeTorque = СилаТормоза * 0.8f;
                    }
                }
            }
            return;
        }
        
        if (Mathf.Abs(verticalInput) < 0.1f)
        {
            // Если отпустили газ и есть КПП, сбрасываем на первую передачу через секунду
            if (ИспользоватьКПП && текущаяПередача != 1 && Time.time > времяСледующегоПереключения + 1f && !вПроцессеПереключения)
            {
                текущаяПередача = 1;
                множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[1];
                максСкоростьТекущейПередачи = МаксСкоростиПоПередачам[1];
                времяСледующегоПереключения = Time.time + ЗадержкаМеждуПереключениями;
            }
            
            float brakeForce = 0f;
            
            if (currentSpeed > 1f)
            {
                if (isMovingForward)
                {
                    brakeForce = СилаТормоза * 0.05f;
                }
                else if (isMovingBackward)
                {
                    brakeForce = СилаТормоза * 0.1f;
                }
            }
            
            if (brakeForce > 0)
            {
                foreach (var wheel in Колёса)
                {
                    wheel.brakeTorque = brakeForce;
                }
            }
        }
    }

    void ОбработатьКППInput()
    {
        if (!ИспользоватьКПП || АвтоматическаяКПП) return;
        
        // Ручное переключение
        if (!вПроцессеПереключения && Time.time > времяСледующегоПереключения)
        {
            if (Input.GetKeyDown(КлавишаПовышенияПередачи) && текущаяПередача < КоличествоПередач)
            {
                ПереключитьПередачуВверх();
            }
            else if (Input.GetKeyDown(КлавишаПониженияПередачи) && текущаяПередача > 0)
            {
                ПереключитьПередачуВниз();
            }
        }
    }

    void HandleHandbrake(bool handbrake)
    {
        if (handbrake != isHandbrakeActive)
        {
            isHandbrakeActive = handbrake;
            
            if (handbrake)
            {
                foreach (var wheel in rearWheels)
                {
                    wheel.sidewaysFriction = handbrakeSidewaysFriction;
                    wheel.brakeTorque = СилаРучногоТормоза;
                }
            }
            else
            {
                foreach (var wheel in rearWheels)
                {
                    wheel.sidewaysFriction = defaultSidewaysFriction;
                    wheel.brakeTorque = 0f;
                }
            }
        }
    }

    void HandleNitro(float verticalInput)
    {
        if (!ИспользоватьНитро) return;
        
        float currentSpeed = rb.linearVelocity.magnitude * 3.6f;
        bool isMovingForward = Vector3.Dot(rb.linearVelocity, transform.forward) > 0.1f;
        
        bool canActivateNitro = Input.GetKey(КлавишаНитро) && 
                               ТекущийЗапасНитро > 0 && 
                               verticalInput > 0.1f && 
                               currentSpeed > МинимальнаяСкоростьДляНитро && 
                               isMovingForward;
        
        if (canActivateNitro && !нитроАктивно)
        {
            нитроАктивно = true;
            
            текущаяМощностьДвигателя = БазоваяМощностьДвигателя * МножительМощностиНитро;
            текущаяМаксимальнаяСкорость = БазоваяМаксимальнаяСкорость * МножительСкоростиНитро;
            
            if (ЗвукНитро != null && !ЗвукНитро.isPlaying)
            {
                ЗвукНитро.Play();
            }
        }
        
        bool shouldDeactivate = нитроАктивно && (!canActivateNitro || ТекущийЗапасНитро <= 0);
        if (shouldDeactivate)
        {
            нитроАктивно = false;
            
            текущаяМощностьДвигателя = БазоваяМощностьДвигателя;
            текущаяМаксимальнаяСкорость = БазоваяМаксимальнаяСкорость;
            
            if (ЗвукНитро != null && ЗвукНитро.isPlaying)
            {
                ЗвукНитро.Stop();
            }
        }
        
        if (нитроАктивно)
        {
            ТекущийЗапасНитро -= Time.deltaTime * (СкоростьРасходаНитро / 100f) * 100f;
            ТекущийЗапасНитро = Mathf.Max(0, ТекущийЗапасНитро);
        }
        else if (ТекущийЗапасНитро < МаксимальныйЗапасНитро)
        {
            ТекущийЗапасНитро += Time.deltaTime * (СкоростьВосстановленияНитро / 100f) * 100f;
            ТекущийЗапасНитро = Mathf.Min(ТекущийЗапасНитро, МаксимальныйЗапасНитро);
        }
    }

    void FixedUpdate()
    {
        // Обновление состояния "в воздухе" и проверка кочек
        ОбновитьСостояниеПрыжкаИКочки();
        
        // Обработка веса и инерции
        ОбработатьВесИИнерцию();
        
        // Обработка КПП (автоматическое переключение)
        ОбработатьКППАвтоматика();
        
        // Обработка физического наклона (только в воздухе)
        if (вВоздухе && !вРежимеОтскока && началНаклоняться)
        {
            ОбработатьФизическийНаклон();
        }
        
        // Обработка отскоков
        ОбработатьОтскоки();
        
        // Стабилизация (только на земле и не в отскоке)
        if (!вВоздухе && !вРежимеОтскока)
        {
            StabilizeCar();
            
            // Возврат к нормальному положению после прыжка
            ВозвратКНормальномуПоложению();
        }
        
        // Демпфирование вращения в воздухе
        if (вВоздухе)
        {
            rb.angularVelocity *= (1f - ДемпфированиеВВоздухе * Time.fixedDeltaTime);
        }
    }

    void ОбработатьВесИИнерцию()
    {
        // Обновляем массу, если она изменилась в инспекторе
        if (Mathf.Abs(rb.mass - МассаАвтомобиля) > 0.1f)
        {
            rb.mass = МассаАвтомобиля;
        }
        
        // Применяем сопротивление качению
        if (колёсНаЗемле > 0 && rb.linearVelocity.magnitude > 0.1f)
        {
            Vector3 противоположнаяСила = -rb.linearVelocity.normalized * СопротивлениеКачению * rb.mass;
            rb.AddForce(противоположнаяСила);
        }
        
        // Применяем силу прижима к земле
        if (колёсНаЗемле > 0)
        {
            rb.AddForce(-transform.up * СилаПрижима * Time.fixedDeltaTime);
        }
        
        // Рассчитываем инерцию поворота
        float скорость = rb.linearVelocity.magnitude;
        float массаФактор = МассаАвтомобиля / 800f; // Нормализуем к базовой массе 800
        
        // Инерция поворота зависит от массы и скорости
        инерцияПоворота = Vector3.Lerp(
            инерцияПоворота, 
            rb.angularVelocity, 
            Time.fixedDeltaTime * (10f / (массаФактор * МножительИнерцииПоворота * (1f + скорость * 0.1f)))
        );
        
        // Инерция разгона (обновляется при ускорении/торможении)
        float ускорениеПоПередаче = текущееУскорение;
        if (Mathf.Abs(ускорениеПоПередаче) > 0.1f)
        {
            инерцияРазгона = Mathf.Lerp(
                инерцияРазгона,
                1f,
                Time.fixedDeltaTime * (5f / (массаФактор * МножительИнерцииРазгона))
            );
        }
        else
        {
            // Быстрее восстанавливаем инерцию при отсутствии ускорения
            инерцияРазгона = Mathf.Lerp(инерцияРазгона, 1f, Time.fixedDeltaTime * 10f);
        }
    }

    void ОбработатьКППАвтоматика()
    {
        if (!ИспользоватьКПП || !АвтоматическаяКПП) return;
        
        float текущаяСкоростьКмЧ = rb.linearVelocity.magnitude * 3.6f;
        
        // Рассчитываем текущие обороты
        текущиеОбороты = РассчитатьОбороты(текущаяСкоростьКмЧ);
        
        // Автоматическое переключение передач с задержкой
        if (!вПроцессеПереключения && Time.time > времяСледующегоПереключения)
        {
            // Для первой передачи - ждем достижения минимальной скорости
            if (текущаяПередача == 1 && текущаяСкоростьКмЧ < МинимальнаяСкоростьДляВторойПередачи)
            {
                return; // Не переключаемся пока не наберем скорость
            }
            
            // Переключение вверх
            if (текущиеОбороты > МаксимальныеОборотыДляПереключения && текущаяПередача < КоличествоПередач)
            {
                ПереключитьПередачуВверх();
            }
            // Переключение вниз
            else if (текущиеОбороты < МинимальныеОборотыДляПереключения && текущаяПередача > 1)
            {
                ПереключитьПередачуВниз();
            }
        }
        
        // Обновляем параметры текущей передачи
        множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[текущаяПередача];
        максСкоростьТекущейПередачи = МаксСкоростиПоПередачам[текущаяПередача];
        
        // Ограничиваем максимальную скорость на текущей передаче
        if (текущаяСкоростьКмЧ > максСкоростьТекущейПередачи)
        {
            // Создаем эффект "ограничителя" - снижаем мощность
            float превышение = текущаяСкоростьКмЧ - максСкоростьТекущейПередачи;
            float ограничение = Mathf.Clamp01(1f - превышение / 10f);
            множительМощностиТекущейПередачи *= ограничение;
        }
    }

    float РассчитатьОбороты(float скоростьКмЧ)
    {
        if (текущаяПередача == 0) return 3000f; // Задняя передача
        
        // Рассчитываем обороты на основе скорости и передачи
        float базовыеОбороты = 1000f;
        float оборотыНаПередаче = 0f;
        
        // Формула: обороты = скорость * коэффициент передачи
        float коэффициентПередачи = 40f + (текущаяПередача * 15f);
        оборотыНаПередаче = базовыеОбороты + (скоростьКмЧ * коэффициентПередачи / максСкоростьТекущейПередачи * 4000f);
        
        // Добавляем случайные колебания для реалистичности
        оборотыНаПередаче += Mathf.Sin(Time.time * 20f) * 100f;
        
        return Mathf.Clamp(оборотыНаПередаче, 800f, 7000f);
    }

    void ПереключитьПередачуВверх()
    {
        if (вПроцессеПереключения || текущаяПередача >= КоличествоПередач) return;
        
        StartCoroutine(ПроцессПереключенияПередачи(true));
    }

    void ПереключитьПередачуВниз()
    {
        if (вПроцессеПереключения || текущаяПередача <= 0) return;
        
        StartCoroutine(ПроцессПереключенияПередачи(false));
    }

    System.Collections.IEnumerator ПроцессПереключенияПередачи(bool повышение)
    {
        вПроцессеПереключения = true;
        
        if (повышение)
        {
            текущаяПередача++;
            Debug.Log($"Переключение на {текущаяПередача} передачу");
        }
        else
        {
            текущаяПередача--;
            Debug.Log($"Переключение на {текущаяПередача} передачу");
        }
        
        // Первая фаза: кратковременное снижение мощности (сцепление)
        float исходныйМножитель = множительМощностиТекущейПередачи;
        множительМощностиТекущейПередачи *= 0.1f; // Сильное снижение
        
        yield return new WaitForSeconds(ДлительностьРывкаПриПереключении * 0.3f);
        
        // Вторая фаза: рывок (включение повышенной передачи)
        вРежимеРывка = true;
        множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[текущаяПередача] * СилаРывкаПриПереключении;
        
        yield return new WaitForSeconds(ДлительностьРывкаПриПереключении * 0.4f);
        
        // Третья фаза: нормализация
        вРежимеРывка = false;
        множительМощностиТекущейПередачи = МножителиМощностиПоПередачам[текущаяПередача];
        
        // Время задержки до следующего переключения
        времяСледующегоПереключения = Time.time + ЗадержкаМеждуПереключениями;
        
        вПроцессеПереключения = false;
    }

    void ОбновитьСостояниеПрыжкаИКочки()
    {
        колёсНаЗемле = 0;
        
        foreach (var колесо in Колёса)
        {
            WheelHit hit;
            if (колесо.GetGroundHit(out hit))
            {
                колёсНаЗемле++;
                
                // Обработка кочек с яркой реакцией
                if (hit.force > 500f && ЧувствительностьККочкам > 0)
                {
                    float скоростьКоэффициент = Mathf.Clamp01(rb.linearVelocity.magnitude / 30f);
                    float силаОтКочки = hit.force * ЧувствительностьККочкам * 0.001f;
                    силаОтКочки += СилаПодбрасыванияОтКочек * скоростьКоэффициент;
                    
                    // Применяем силу вверх с небольшим случайным смещением для эффекта
                    Vector3 направлениеСилы = Vector3.up + 
                        transform.right * Random.Range(-0.2f, 0.2f) + 
                        transform.forward * Random.Range(-0.1f, 0.1f);
                    
                    rb.AddForce(направлениеСилы.normalized * силаОтКочки, ForceMode.Impulse);
                    
                    // Легкая раскачка
                    float раскачка = Random.Range(-0.3f, 0.3f) * силаОтКочки * 0.05f;
                    rb.AddTorque(transform.right * раскачка, ForceMode.Impulse);
                }
            }
        }
        
        bool былаВВоздухе = вВоздухе;
        вВоздухе = колёсНаЗемле < 2;
        
        if (!былаВВоздухе && вВоздухе)
        {
            // Начало прыжка
            времяВВоздухе = 0f;
            начальнаяСкоростьПрыжка = rb.linearVelocity;
            началНаклоняться = false;
            времяСтартаНаклона = Time.time + ЗадержкаНаклона;
            
            // Определяем, какие колеса первыми оторвались
            ОпределитьТипПрыжка();
        }
        else if (былаВВоздухе && !вВоздухе && !вРежимеОтскока)
        {
            // Приземление - запускаем отскок
            ЗапуститьОтскок();
        }
        
        if (вВоздухе)
        {
            времяВВоздухе += Time.fixedDeltaTime;
            
            // Проверяем, можно ли начинать наклон
            if (!началНаклоняться && Time.time >= времяСтартаНаклона)
            {
                началНаклоняться = true;
            }
        }
    }

    void ОпределитьТипПрыжка()
    {
        // Определяем, какие колеса первыми оторвались от земли
        bool передниеНаЗемле = false;
        bool задниеНаЗемле = false;
        
        foreach (var колесо in frontWheels)
        {
            WheelHit hit;
            if (колесо.GetGroundHit(out hit))
            {
                передниеНаЗемле = true;
                break;
            }
        }
        
        foreach (var колесо in rearWheels)
        {
            WheelHit hit;
            if (колесо.GetGroundHit(out hit))
            {
                задниеНаЗемле = true;
                break;
            }
        }
        
        // Если задние колеса еще на земле, а передние уже в воздухе - это съезд с трамплина
        передниеВВоздухеПервыми = !передниеНаЗемле && задниеНаЗемле;
    }

    void ОбработатьФизическийНаклон()
    {
        // Получаем текущие углы Эйлера (в локальных координатах)
        Vector3 локальныеУглы = transform.localEulerAngles;
        текущийУголНаклонаX = локальныеУглы.x > 180 ? локальныеУглы.x - 360 : локальныеУглы.x;
        текущийУголНаклонаZ = локальныеУглы.z > 180 ? локальныеУглы.z - 360 : локальныеУглы.z;
        
        // Вычисляем целевой угол наклона вперед
        float целевойУголВперед = 0f;
        
        // Если передние колеса первыми ушли в воздух (трамплин) - наклон вперед сильнее
        if (передниеВВоздухеПервыми)
        {
            целевойУголВперед = МаксУголНаклонаВперед;
        }
        else
        {
            // Обычный прыжок - легкий наклон вперед
            целевойУголВперед = МаксУголНаклонаВперед * 0.3f;
        }
        
        // Учитываем влияние скорости на наклон
        float влияниеСкорости = Mathf.Clamp01(rb.linearVelocity.magnitude / 40f) * ВлияниеСкоростиНаНаклон;
        целевойУголВперед *= (1f + влияниеСкорости);
        
        // Вычисляем разницу между текущим и целевым углом
        float разницаВперед = целевойУголВперед - текущийУголНаклонаX;
        
        // Применяем физический крутящий момент для наклона вперед
        if (Mathf.Abs(разницаВперед) > 1f)
        {
            // Сила наклона зависит от разницы углов (пропорциональный контроллер)
            float силаНаклона = разницаВперед * СилаНаклонаВперед * Time.fixedDeltaTime;
            
            // Ограничиваем максимальную силу
            силаНаклона = Mathf.Clamp(силаНаклона, -СилаНаклонаВперед * 0.1f, СилаНаклонаВперед * 0.1f);
            
            // Применяем крутящий момент по локальной оси X (наклон вперед/назад)
            rb.AddRelativeTorque(Vector3.right * силаНаклона, ForceMode.Force);
        }
        
        // Подъем задней части при отталкивании от трамплина (задержка)
        if (передниеВВоздухеПервыми && времяВВоздухе > 0.2f)
        {
            float целевойПодъемЗадней = МаксУголПодъемаЗаднейЧасти;
            float разницаЗадней = целевойПодъемЗадней - текущийУголНаклонаX;
            
            if (Mathf.Abs(разницаЗадней) > 1f)
            {
                float силаПодъема = разницаЗадней * СилаПодъемаЗаднейЧасти * Time.fixedDeltaTime * 0.5f;
                силаПодъема = Mathf.Clamp(силаПодъема, -СилаПодъемаЗаднейЧасти * 0.05f, СилаПодъемаЗаднейЧасти * 0.05f);
                
                rb.AddRelativeTorque(Vector3.right * силаПодъема, ForceMode.Force);
            }
        }
        
        // Легкое влияние управления на наклон в воздухе
        float horizontalInput = Input.GetAxis("Horizontal");
        if (Mathf.Abs(horizontalInput) > 0.1f)
        {
            // Наклон в сторону при повороте в воздухе (ограниченный)
            float силаБоковогоНаклона = -horizontalInput * 50f * Time.fixedDeltaTime;
            rb.AddRelativeTorque(Vector3.forward * силаБоковогоНаклона, ForceMode.Force);
        }
    }

    void ВозвратКНормальномуПоложению()
    {
        // Получаем текущие углы
        Vector3 локальныеУглы = transform.localEulerAngles;
        текущийУголНаклонаX = локальныеУглы.x > 180 ? локальныеУглы.x - 360 : локальныеУглы.x;
        текущийУголНаклонаZ = локальныеУглы.z > 180 ? локальныеУглы.z - 360 : локальныеУглы.z;
        
        // Если машина наклонена, плавно возвращаем в нормальное положение
        if (Mathf.Abs(текущийУголНаклонаX) > 1f || Mathf.Abs(текущийУголНаклонаZ) > 1f)
        {
            // Вычисляем силу возврата (пропорциональную углу наклона)
            float силаВозвратаX = -текущийУголНаклонаX * СилаВозвратаКНормальному * Time.fixedDeltaTime;
            float силаВозвратаZ = -текущийУголНаклонаZ * СилаВозвратаКНормальному * Time.fixedDeltaTime;
            
            // Ограничиваем силу
            силаВозвратаX = Mathf.Clamp(силаВозвратаX, -СилаВозвратаКНормальному * 0.05f, СилаВозвратаКНормальному * 0.05f);
            силаВозвратаZ = Mathf.Clamp(силаВозвратаZ, -СилаВозвратаКНормальному * 0.05f, СилаВозвратаКНормальному * 0.05f);
            
            // Применяем крутящий момент для возврата
            rb.AddRelativeTorque(Vector3.right * силаВозвратаX, ForceMode.Force);
            rb.AddRelativeTorque(Vector3.forward * силаВозвратаZ, ForceMode.Force);
        }
    }

    void ЗапуститьОтскок()
    {
        вРежимеОтскока = true;
        времяОтскока = 0f;
        
        // Рассчитываем силу отскока на основе скорости приземления
        float скоростьПриземления = Mathf.Clamp(rb.linearVelocity.magnitude, 0, 30f);
        силаОтскока = СилаОтскока + (СилаОтскока * МножительОтскокаОтСкорости * (скоростьПриземления / 30f));
        
        // Направление отскока - вверх с небольшим случайным смещением
        направлениеОтскока = Vector3.up + 
            transform.right * Random.Range(-0.05f, 0.05f) + 
            transform.forward * Random.Range(-0.03f, 0.03f);
        направлениеОтскока = направлениеОтскока.normalized;
        
        Debug.Log($"Отскок! Сила: {силаОтскока:F1}, Скорость приземления: {скоростьПриземления:F1}");
    }

    void ОбработатьОтскоки()
    {
        if (вРежимеОтскока)
        {
            времяОтскока += Time.fixedDeltaTime;
            
            // Длительность отскока (аркадный, быстрый отскок)
            float длительностьОтскока = 0.2f;
            
            if (времяОтскока <= длительностьОтскока)
            {
                // Плавная кривая силы отскока (синусоида)
                float прогресс = времяОтскока / длительностьОтскока;
                float текущаяСила = силаОтскока * Mathf.Sin(прогресс * Mathf.PI);
                
                // Применяем силу отскока
                rb.AddForce(направлениеОтскока * текущаяСила, ForceMode.Force);
                
                // Легкая раскачка при отскоке
                if (прогресс > 0.3f && прогресс < 0.7f)
                {
                    float раскачка = Mathf.Sin((прогресс - 0.3f) * Mathf.PI * 2.5f) * силаОтскока * 0.01f;
                    rb.AddRelativeTorque(Vector3.right * раскачка, ForceMode.Force);
                }
            }
            else
            {
                // Завершение отскока
                вРежимеОтскока = false;
                
                // Плавное восстановление после отскока
                StartCoroutine(ВосстановлениеПослеОтскока());
            }
        }
    }

    System.Collections.IEnumerator ВосстановлениеПослеОтскока()
    {
        float времяВосстановления = 0.3f;
        float elapsed = 0f;
        
        Vector3 начальныеУглы = transform.localEulerAngles;
        Vector3 целевыеУглы = new Vector3(0, начальныеУглы.y, 0);
        
        while (elapsed < времяВосстановления)
        {
            elapsed += Time.deltaTime;
            float progress = elapsed / времяВосстановления;
            float smoothProgress = Mathf.SmoothStep(0f, 1f, progress);
            
            // Плавный поворот к целевому углу
            Quaternion целевойПоворот = Quaternion.Euler(целевыеУглы);
            transform.rotation = Quaternion.Slerp(transform.rotation, целевойПоворот, 
                smoothProgress * СкоростьВосстановленияПослеОтскока * Time.deltaTime);
            
            yield return null;
        }
    }

    void StabilizeCar()
    {
        if (колёсНаЗемле > 1)
        {
            Vector3[] rayStarts = new Vector3[]
            {
                transform.position + transform.right * 1f + transform.up * 0.5f,
                transform.position - transform.right * 1f + transform.up * 0.5f
            };

            float rayLength = 2f;
            RaycastHit hit;
            
            for (int i = 0; i < rayStarts.Length; i++)
            {
                if (!Physics.Raycast(rayStarts[i], -transform.up, out hit, rayLength))
                {
                    Vector3 forcePoint = transform.position + (i == 0 ? transform.right : -transform.right) * 1f;
                    rb.AddForceAtPosition(-transform.up * СилаПротивОпрокидывания * Time.fixedDeltaTime, forcePoint);
                }
            }
        }
    }

