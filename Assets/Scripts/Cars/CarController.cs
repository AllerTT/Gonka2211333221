        DrawOutlinedLabel(new Rect(startX, startY, 250, 25), 
            $"Масса: {МассаАвтомобиля:F0} кг | Инерция: {инерцияРазгона:F2}", 
            массаЦвет, Color.black, outlinedStyle);
        
        // Управление КПП (только для ручного режима)
        if (ИспользоватьКПП && !АвтоматическаяКПП)
        {
            startY += lineHeight;
            DrawOutlinedLabel(new Rect(startX, startY, 300, 25), 
                $"Управление: Shift - вверх, Ctrl - вниз", 
                Color.white, Color.black, outlinedStyle);
        }
        
        // Информация о наклоне кузова
        startY += lineHeight;
        DrawOutlinedLabel(new Rect(startX, startY, 300, 25), 
            $"Наклон кузова: {текущийНаклонКузова:F1}°", 
            Mathf.Abs(текущийНаклонКузова) > 5f ? Color.yellow : Color.white, 
            Color.black, outlinedStyle);
    }

    void DrawOutlinedLabel(Rect rect, string text, Color textColor, Color outlineColor, GUIStyle style)
    {
        Color originalColor = GUI.color;
        
        style.normal.textColor = outlineColor;
        
        GUI.Label(new Rect(rect.x - 1, rect.y - 1, rect.width, rect.height), text, style);
        GUI.Label(new Rect(rect.x + 1, rect.y - 1, rect.width, rect.height), text, style);
        GUI.Label(new Rect(rect.x - 1, rect.y + 1, rect.width, rect.height), text, style);
        GUI.Label(new Rect(rect.x + 1, rect.y + 1, rect.width, rect.height), text, style);
        
        style.normal.textColor = textColor;
        GUI.Label(rect, text, style);
        
        GUI.color = originalColor;
    }
